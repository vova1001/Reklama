  await next(page);
  await page.waitForURL(`**/app/tasks/${id}?sent=1`);
  await expect(page.locator('[data-status-label]')).toHaveText('Опубликовано');
  await expect(page.locator('.terms')).toContainText('Ужин на двоих');
